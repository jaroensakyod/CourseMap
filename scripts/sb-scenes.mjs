// Scan every exported *Scene in the episode kits and write the storyboard scene registry (src/storyboard/scenes.gen.ts).
// Usage: node scripts/sb-scenes.mjs   (run again after adding or exporting new scenes)
// A scene = ({ id, start, end, ...cues }) => <V2 …/>. Extra numeric props are cue frames (an impact, a flag going
// up…): the storyboard passes the panel's `cue` frame for them, and [cue, cue+24, cue+48] for number[] props.
// Ids are kebab-case names; the catalogue (src/storyboard/catalog.json) adds a Thai description, tags and sound.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

// Only illustration-style-v2 kits (house standard): EP.4, EP.5 and new scenes in src/storyboard/scenes/.
const roots = ["src/episodes/thaihistory/ep04", "src/episodes/thaihistory/ep05", "src/storyboard/scenes"];
const files = [];
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.tsx$/.test(f)) files.push(p);
  }
};
roots.forEach((r) => existsSync(r) && walk(r));

const kebab = (s) => s.replace(/Scene$/, "").replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const entries = [];
const seen = new Map();
for (const f of files.sort()) {
  const s = readFileSync(f, "utf8");
  // `({ … }: { … })`, `({ … }: Sc)` or `({ … }: Sc & { … })`
  for (const m of s.matchAll(/^export const ([A-Z][A-Za-z0-9]*Scene) = \(\{[^}]*\}: (?:\{([^}]*)\}|Sc(?: & \{([^}]*)\})?)\)/gm)) {
    const name = m[1];
    const types = m[2] ?? m[3] ?? "";
    const props = {};
    for (const part of types.split(";")) {
      const t = part.trim().match(/^(\w+)(\?)?:\s*(.+)$/);
      if (!t || ["id", "start", "end"].includes(t[1])) continue;
      props[t[1]] = { type: t[3].trim(), optional: !!t[2] };
    }
    let id = kebab(name);
    const n = (seen.get(id) ?? 0) + 1;
    seen.set(id, n);
    if (n > 1) id = `${id}-${n}`;
    const from = relative("src/storyboard", f).replace(/\\/g, "/").replace(/\.tsx$/, "");
    entries.push({ id, name, from, props });
  }
}

const imports = new Map();
for (const e of entries) {
  if (!imports.has(e.from)) imports.set(e.from, []);
  imports.get(e.from).push(e);
}
const alias = (e) => `${e.name}_${e.from.replace(/[^A-Za-z0-9]/g, "_")}`;
const propCode = (e) => {
  const out = [];
  for (const [k, { type, optional }] of Object.entries(e.props)) {
    if (type === "number") out.push(`${k}: cue`);
    else if (type === "number[]") out.push(`${k}: [cue, cue + 24, cue + 48]`);
    else if (k === "anchor") out.push(`anchor`);
    else if (k === "sky" && !optional) out.push(`sky: ["#3a4a6a", "#e8b070"]`);
    else if (k === "light" && !optional) out.push(`light: [0.8, 0.25]`);
    else if (!optional && /"fr"/.test(type)) out.push(`${k}: "fr"`);
  }
  return out.join(", ");
};

let code = `// GENERATED by scripts/sb-scenes.mjs — do not edit. ${entries.length} scenes.\nimport type { ComponentType, ReactElement } from "react";\n`;
for (const [from, list] of imports) code += `import { ${list.map((e) => `${e.name} as ${alias(e)}`).join(", ")} } from "${from.startsWith(".") ? from : "./" + from}";\n`;
code += `\nexport type SceneRender = (p: { id: string; start: number; end: number; cue: number; anchor: [number, number] }) => ReactElement;\n`;
code += `// eslint-disable-next-line @typescript-eslint/no-explicit-any\nconst c = (C: ComponentType<any>) => C;\n`;
code += `export const SCENES: Record<string, SceneRender> = {\n`;
for (const e of entries) {
  const p = propCode(e);
  code += `  "${e.id}": ({ id, start, end, cue, anchor }) => { const C = c(${alias(e)}); void cue; void anchor; return <C id={id} start={start} end={end}${p ? ` {...{ ${p} }}` : ""} />; },\n`;
}
code += `};\nexport const SCENE_SOURCES: Record<string, string> = {\n${entries.map((e) => `  "${e.id}": "${e.from}#${e.name}",`).join("\n")}\n};\n`;
writeFileSync("src/storyboard/scenes.gen.tsx", code);
console.log(`wrote src/storyboard/scenes.gen.tsx — ${entries.length} scenes`);
