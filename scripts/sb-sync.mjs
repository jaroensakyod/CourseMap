// Register every storyboard episode (a folder under src/episodes with episode.json + beats.json) as compositions.
// Usage: node scripts/sb-sync.mjs   (npm run sb:sync — the episode command runs it for you)
// Writes src/storyboard/registry.gen.ts. Missing timing.json → a draft one (scripts/timing-draft.mjs: silent audio,
// even word timing) so stills can be checked before any voice is made; tts-gemini.mjs replaces draft beats.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const eps = [];
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (f === "episode.json" && existsSync(join(d, "beats.json"))) eps.push(d);
  }
};
walk("src/episodes");

const out = [];
for (const dir of eps.sort()) {
  const slug = relative("src/episodes", dir).replace(/\\/g, "/");
  const tf = join(dir, "timing.json");
  // No timing yet, or draft timing whose silent audio is missing (fresh clone): make the draft (silent WAVs).
  const t = existsSync(tf) ? JSON.parse(readFileSync(tf, "utf8")) : null;
  if (!t || t.some((b) => b.draft && !existsSync(join("public", b.file)))) {
    console.log(`  ${slug}: draft timing (silent audio) for stills`);
    execFileSync("node", ["scripts/timing-draft.mjs", slug], { stdio: "inherit" });
  }
  out.push(slug);
}
const id = (slug) => "SB-" + slug.replace(/[^A-Za-z0-9]+/g, "-");
let code = `// GENERATED by scripts/sb-sync.mjs — do not edit.\nimport type { SbData } from "./Storyboard";\n`;
out.forEach((slug, i) => {
  const rel = `../episodes/${slug}`;
  code += `import e${i} from "${rel}/episode.json";\nimport b${i} from "${rel}/beats.json";\nimport t${i} from "${rel}/timing.json";\n`;
});
code += `\nexport const SB_EPISODES: { id: string; data: SbData }[] = [\n`;
out.forEach((slug, i) => {
  code += `  { id: "${id(slug)}", data: { slug: "${slug}", episode: e${i} as unknown as SbData["episode"], beats: b${i} as unknown as SbData["beats"], timing: t${i} as unknown as SbData["timing"] } },\n`;
});
code += `];\n`;
writeFileSync("src/storyboard/registry.gen.ts", code);
console.log(`storyboard episodes: ${out.length ? out.map(id).join(", ") : "none"}`);
